CREATE TABLE IF NOT EXISTS kbos_showcases (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 slug text NOT NULL UNIQUE,
 project_id uuid REFERENCES kbos_projects(id) ON DELETE SET NULL,
 contact_id uuid REFERENCES kbos_contacts(id) ON DELETE SET NULL,
 status text NOT NULL DEFAULT 'draft',
 basis text NOT NULL DEFAULT 'consent',
 service text NOT NULL DEFAULT 'audiovisual',
 title text NOT NULL,
 category text,
 client_name text,
 client_logo text,
 year text,
 description text,
 long_description text,
 about jsonb,
 img text,
 gallery jsonb,
 video_label text,
 video_id text,
 site_url text,
 metrics text,
 testimonial text,
 testimonial_author text,
 content_hash text,
 published_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS kbos_showcase_consents (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 showcase_id uuid NOT NULL REFERENCES kbos_showcases(id) ON DELETE CASCADE,
 token_hash text NOT NULL UNIQUE,
 status text NOT NULL DEFAULT 'pending',
 requested_scopes jsonb NOT NULL,
 granted_scopes jsonb,
 snapshot jsonb NOT NULL,
 content_hash text NOT NULL,
 signer_name text,
 expires_at timestamptz NOT NULL,
 decided_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS kbos_showcase_consents_showcase_idx ON kbos_showcase_consents (showcase_id, created_at DESC)
